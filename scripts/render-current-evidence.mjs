import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { AkeDataRepository } from '../src/core/ake-data-repository.mjs';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(projectRoot, 'docs', 'evidence', 'current-snapshot.md');
const checkOnly = process.argv.includes('--check');

async function readJson(relativePath) {
    return JSON.parse(await readFile(path.join(projectRoot, relativePath), 'utf8'));
}

function percent(value) {
    return `${(Number(value) * 100).toFixed(2)}%`;
}

function yesNo(value) {
    return value ? '是' : '否';
}

const [lock, tableManifest, runtimeManifest, analysisManifest, actionAudit, eventAudit, operatorAudit, timing] = await Promise.all([
    readJson('sources.lock.json'),
    readJson('reference/public-data/akedata/table-corpus.manifest.json'),
    readJson('reference/public-data/akedata/runtime-corpus.manifest.json'),
    readJson('derived/ake-analysis/manifest.json'),
    readJson('derived/cleanroom/ake-action-coverage.json'),
    readJson('derived/cleanroom/ake-ability-event-audit.json'),
    readJson('derived/cleanroom/ake-operator-mechanism-audit.json'),
    readJson('derived/cleanroom/ake-timing-profiles.json')
]);
const catalog = new AkeDataRepository({ projectRoot }).catalog();
const action = actionAudit.totals;
const event = eventAudit.summary;
const operator = operatorAudit.summary;
const missing = runtimeManifest.discovery.missing ?? [];
const timingProfiles = Object.values(timing.characters ?? {})
    .flatMap(character => character.profiles ?? []);
const timingDiagnostics = timingProfiles.filter(profile => profile.diagnostic);

const markdown = `<!-- GENERATED by scripts/render-current-evidence.mjs. DO NOT EDIT. -->
# 当前证据快照

本页是当前固定数据、生成审计与目录规模的唯一人类可读快照。它由仓库生成，不接受手工修数；架构页只解释口径，所有会漂移的数字引用本页或对应 JSON。

## 来源锁

| 证据 | 当前固定值 |
| --- | --- |
| AKE TableCfg | \`${lock.pins.akedataTableVersion}\` |
| AKE JSON revision | \`${lock.pins.akedataJsonRevision}\` |
| TableCfg shared revision | \`${tableManifest.sharedRevision}\` |
| AKEDatabase 参考提交 | \`${lock.pins.akeDatabaseCommit}\` |
| Calc 数据版本 | \`${lock.pins.calcDataVersion}\` |
| Calc bundle | \`${lock.pins.calcBundle}\` |
| source records | ${lock.sources.length} |

完整 URL、文件大小、逐文件 SHA-256 与语料聚合哈希位于 [\`sources.lock.json\`](../../sources.lock.json)。

## 目录规模

| 目录 | 数量 | 口径 |
| --- | ---: | --- |
| 角色条目 | ${catalog.characters.length} | 包含抽象共享角色条目 |
| 已审计可选角色 | ${operatorAudit.auditedCharacterCount} | 排除 \`${operatorAudit.source.excludedAbstractCharacters.join('`, `')}\` |
| timing 角色 | ${Object.keys(timing.characters ?? {}).length} | 可生成前端预演画像的角色 |
| timing 技能画像 | ${timingProfiles.length} | 当前目录中的技能变体 |
| diagnostic fallback | ${timingDiagnostics.length} | 运行探针未闭合，只提供静态结构画像 |
| 参考分析样本 | ${analysisManifest.recordCount} | 来源锁明示、第三方分析器生成，不是运行时输入 |
| 武器 | ${catalog.weapons.length} | 当前 AKE 目录 |
| 装备 | ${catalog.equipment.length} | 当前 AKE 目录 |
| 套装 | ${catalog.suits.length} | 当前 AKE 目录 |

## 语料完整性

| 语料 | 文件数 | 内容哈希 |
| --- | ---: | --- |
| TableCfg | ${Object.keys(tableManifest.files ?? {}).length} | \`${tableManifest.contentHash}\` |
| 索引运行时语料 | ${runtimeManifest.files} | \`${runtimeManifest.contentHash}\` |
| 递归依赖闭包 | ${runtimeManifest.discovery.resolved} | \`${runtimeManifest.discovery.contentHash}\` |
| 索引外补充文件 | ${runtimeManifest.discovery.supplementalFiles.length} | 已纳入依赖闭包哈希 |
| 明确缺失依赖 | ${missing.length} | 不生成空定义 |

资产索引 SHA-256 为 \`${runtimeManifest.indexSha256}\`。\`npm run check:consistency\` 会重新读取每个文件、校验逐文件哈希、重建两类聚合哈希，并从当前表重新遍历依赖闭包。

## 生成审计

### 动作覆盖

权威报告：[\`ake-action-coverage.json\`](../../derived/cleanroom/ake-action-coverage.json)

| 指标 | 当前值 |
| --- | ---: |
| 扫描文件 | ${action.files} |
| 动作出现 | ${action.actionOccurrences} |
| 唯一动作类型 | ${action.uniqueActionTypes} |
| executable | ${action.compilerStatuses.executable} |
| metadata-only | ${action.compilerStatuses['metadata-only']} |
| unresolved | ${action.compilerStatuses.unresolved} |
| gameplay compiler coverage | ${percent(action.gameplayCompilerCoverage)} |
| calculator-core complete coverage | ${percent(action.calculatorCore.completeCoverage)} |
| calculator-core executable-route coverage | ${percent(action.calculatorCore.executableRouteCoverage)} |

### 能力事件覆盖

权威报告：[\`ake-ability-event-audit.json\`](../../derived/cleanroom/ake-ability-event-audit.json)

| 指标 | 当前值 |
| --- | ---: |
| 事件键 | ${event.eventKeys} |
| 消费者组 | ${event.consumerGroups} |
| 生产者完整事件类型 | ${event.completeEventTypes} |
| 生产者完整消费者组 | ${event.completeConsumerGroups} |
| 缺少生产者事件类型 | ${event.missingEmitterEventTypes} |
| 缺少生产者消费者组 | ${event.missingEmitterConsumerGroups} |
| 非法事件值 | ${event.invalidEventValues} |
| 非法消费者组 | ${event.invalidConsumerGroups} |

### 逐角色机制风险

权威报告：[\`ake-operator-mechanism-audit.json\`](../../derived/cleanroom/ake-operator-mechanism-audit.json)

| 指标 | 当前值 |
| --- | ---: |
| 已审计角色 | ${operatorAudit.auditedCharacterCount} |
| findings | ${operator.findingCount} |
| combat risks | ${operator.combatRiskCount} |
| combat-blocking | ${operator.byImpact['combat-blocking']} |
| combat-partial | ${operator.byImpact['combat-partial']} |
| evidence-missing | ${operator.byImpact['evidence-missing']} |
| spatial-assumption | ${operator.byImpact['spatial-assumption']} |
| presentation-only | ${operator.byImpact['presentation-only']} |
| combat closed | ${yesNo(operator.isCombatClosed)} |

## 明确缺失的上游依赖

${missing.length > 0 ? missing.map(file => `- \`${file}\``).join('\n') : '- 无。'}

这些路径由当前表和运行时 JSON 的真实引用产生，但当前固定源未提供对应文件。它们保持缺失并进入审计；不得用猜测、空对象或角色特例伪造闭包。

## 结论边界

本页可以证明当前输入版本、文件完整性、目录规模和审计分类已经彼此对齐；不能证明全部角色、配装、敌人和空间场景行为精确。\`combat closed = 否\` 是当前事实。行为精确度仍只由冻结 Calc oracle 和明确的角色机制场景逐项证明。
`;

if (checkOnly) {
    let current = '';
    try {
        current = await readFile(outputPath, 'utf8');
    } catch (error) {
        if (error.code !== 'ENOENT') throw error;
    }
    if (current !== markdown) {
        console.error('EVIDENCE_DOC_STALE docs/evidence/current-snapshot.md; run npm run docs:evidence');
        process.exitCode = 1;
    } else {
        console.log('EVIDENCE_DOC_OK docs/evidence/current-snapshot.md');
    }
} else {
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, markdown);
    console.log('wrote docs/evidence/current-snapshot.md');
}
